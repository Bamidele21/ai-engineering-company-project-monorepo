def supplier_exists(table, supplier: Supplier) -> bool:
    supplier_query = Query()
    return (
        table.get(
            (supplier_query.name == supplier.name)
            & (supplier_query.country == supplier.country)
        )
        is not None
    )


def main() -> None:
    inserted_count = 0
    with TinyDB(DB_FILE) as db:
        suppliers_table = db.table(TABLE_NAME)

        for raw_supplier in SUPPLIERS_SEED:
            supplier = Supplier(**raw_supplier)
            if supplier_exists(suppliers_table, supplier):
                continue

            storable_supplier = supplier.model_dump()
            storable_supplier["updated_at"] = supplier.updated_at.isoformat()
            suppliers_table.insert(storable_supplier)
            inserted_count += 1

    print(f"Seed completed. Inserted records: {inserted_count}")


if __name__ == "__main__":
    main()